export function path(lang: Lang, p = '') {
  const clean = p.replace(/^\/+|\/+$/g, '');
  return `/${lang}/${clean ? `${clean}/` : ''}`;
}

export function formatDate(d: Date, lang: Lang) {
  return new Intl.DateTimeFormat(lang === 'ko' ? 'ko-KR' : 'en-US', {
    year: 'numeric',
    month: lang === 'ko' ? 'long' : 'short',
    day: 'numeric',
  }).format(d);
}
